export default function HomeDesktop() {
  const { openMobileMenu, openServicesModal } = useModal();
  const [isMobile, setIsMobile] = useState(false);
  const [isMobileMenuOpen, setIsMobileMenuOpen] =
    useState(false);

  useEffect(() => {
    const checkMobile = () =>
      setIsMobile(window.innerWidth < 768);
    checkMobile();
    window.addEventListener("resize", checkMobile);
    return () =>
      window.removeEventListener("resize", checkMobile);
  }, []);

  const handleMobileMenuClick = () => {
    setIsMobileMenuOpen(!isMobileMenuOpen);
    openMobileMenu();
  };

  return (
    <div
      className="bg-white dark:bg-[#0a0a0a] content-stretch flex flex-col items-start relative size-full transition-colors duration-300"
      data-name="Home • Desktop"
    >
      {/* Mobile Header */}
      {isMobile && (
        <MobileHeader
          onMenuClick={handleMobileMenuClick}
          isMenuOpen={isMobileMenuOpen}
        />
      )}

      <Frame
        onOpenMenu={openMobileMenu}
        onOpenServices={openServicesModal}
        isMobile={isMobile}
      />
    </div>
  );
}